"""Run the queries in database/sql/queries.sql and database/mongo/queries.js
against the loaded databases and write the real results to
reports/db_query_results.md.

Usage (repo root):  python scripts/run_db_queries.py
"""
import json
import re
import sys
from datetime import date, datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))  # allow `python scripts/...` from the repo root

from bson import json_util  # noqa: E402

from src.db.mongo import get_client, get_collection  # noqa: E402
from src.db.sql import get_engine  # noqa: E402

SQL_FILE = ROOT / "database" / "sql" / "queries.sql"
MONGO_FILE = ROOT / "database" / "mongo" / "queries.js"
OUT_FILE = ROOT / "reports" / "db_query_results.md"


def split_named_blocks(text, marker):
    """Return [(name, block_text)] for each block that starts with `marker name`."""
    parts = re.split(rf"^{re.escape(marker)}\s*(\w+)\s*$", text, flags=re.MULTILINE)
    return [(parts[i], parts[i + 1].strip()) for i in range(1, len(parts), 2)]


def parse_pipeline(block):
    """Extract the aggregate([...]) pipeline from a mongosh block as Python objects."""
    pipeline = re.search(r"aggregate\((\[.*\])\)\.toArray", block, flags=re.DOTALL).group(1)
    # ISODate("...") is mongosh syntax; Extended JSON {"$date": ...} is its JSON form
    pipeline = re.sub(r'ISODate\("([^"]+)"\)', r'{"$date": "\1"}', pipeline)
    return json_util.loads(pipeline)


def fmt(value):
    if value is None:
        return "NULL"
    if isinstance(value, datetime):
        if value.tzinfo is None:  # MySQL DATETIME values are naive UTC
            value = value.replace(tzinfo=timezone.utc)
        return value.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    if isinstance(value, date):
        return value.isoformat()
    if isinstance(value, dict):
        return json.dumps(value)
    return str(value)


def to_markdown(rows):
    if not rows:
        return "_(no rows)_"
    headers = list(rows[0])
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(fmt(r.get(h)) for h in headers) + " |" for r in rows]
    return "\n".join(lines)


def run_sql():
    sections = []
    with get_engine().connect() as conn:
        for name, block in split_named_blocks(SQL_FILE.read_text(), "-- name:"):
            # exec_driver_sql: run the text verbatim (no SQLAlchemy bind parsing)
            rows = [dict(r._mapping) for r in conn.exec_driver_sql(block)]
            sections.append((name, "sql", block, rows))
    return sections


def run_mongo():
    coll = get_collection(get_client())
    sections = []
    for name, block in split_named_blocks(MONGO_FILE.read_text(), "// name:"):
        rows = list(coll.aggregate(parse_pipeline(block)))
        sections.append((name, "javascript", block, rows))
    return sections


def main():
    out = ["# Database query results",
           "",
           f"Generated by `scripts/run_db_queries.py` on "
           f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}. "
           "All timestamps are UTC. Results are the actual output of each query.",
           ""]
    for title, sections in (("MySQL", run_sql()), ("MongoDB", run_mongo())):
        out += [f"## {title}", ""]
        for name, lang, block, rows in sections:
            out += [f"### {name}", "", f"```{lang}", block, "```", "",
                    f"Result ({len(rows)} rows):", "", to_markdown(rows), ""]
            print(f"{title} {name}: {len(rows)} rows")
    OUT_FILE.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {OUT_FILE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
